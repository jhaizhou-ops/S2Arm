// 宏（MME）程序离线编译生成器：迁自旧库 ryu_judge/core/MacroGen.cs（10-19 架构线），只改入口与路径。
// 用法：dotnet run -c Release --project graphics/tools/macrogen --artifacts-path <仓外目录> -- <输出 S2AMacroTable.g.cs> <导出目录>…
//   导出目录 = 局里 S2A_MACRO_DUMP=<目录> 导出的 <哈希>.mme（表外的宏首次出现时导出，见 S2AMacroAot.ReportMiss）。
//   语料按游戏放 ~/.s2arm/run/s2arm/macro/<游戏>/（游戏数据派生，不进仓库）；输出写进 compat/tree/src/Ryujinx.Graphics.Gpu/Engine/MME/S2AMacroTable.g.cs 后，
//   按 compat/README.md 走 patch_new.sh 出补丁（生成表属 Ryujinx 树内源码）。
// 宏（MME）程序离线编译生成器（10-19 架构线）：ryu_judge --macrogen <输出 .cs> <导出目录>…
// 输入：S2A_MACRO_DUMP 导出的 <哈希>.mme（小端 int32 字，范围 = S2AMacroAot.Analyze）。输出：Ryujinx.Graphics.Gpu 里 S2AMacroAot.Register 的实现，
// 每个程序一个静态方法 + 代码全文（运行时命中后逐字比）。翻译照 MacroJitCompiler 的结构（分支目标打标签、延迟槽内联、退出后再执行一条），
// 每条指令的求值式逐字照 MacroInterpreter（AOT 下原本跑的就是它；两者在加减进位上并不一致：解释器 (ulong)int 是符号扩展，JIT 的 conv.u8 是零扩展，这里取解释器）。
// 不可编的（见 S2AMacroAot.Analyze）跳过并列出原因，运行时照旧解释器。
// 语料按游戏放 sw/gfx/macro/<游戏>/（Mac 局 S2A_MACRO_DUMP=<目录> 导出后拷进来）；重生成：
//   ryu_judge --macrogen sw/third_party/ryujinx_gpu/src/Ryujinx.Graphics.Gpu/Engine/MME/S2AMacroTable.g.cs sw/gfx/macro/*
// 生成文件在 Ryujinx.Graphics.Gpu 目录内：工程按目录收源码、tools/nxaot.sh 的缓存键对 sw/third_party/ryujinx_gpu 全树取哈希，两者都自动带上它。
using Ryujinx.Graphics.Gpu.Engine.MME;
using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Runtime.InteropServices;
using System.Text;

namespace S2A.MacroGen
{
    public static class MacroGen
    {
        public static int GenCmd(string[] args)
        {
            if (args.Length < 2)
            {
                Console.Error.WriteLine("用法：macrogen <输出 S2AMacroTable.g.cs> <导出目录>…");
                return 2;
            }

            string outPath = args[0];
            SortedDictionary<ulong, int[]> progs = new();
            int files = 0;

            foreach (string dir in args[1..])
            {
                foreach (string f in Directory.GetFiles(dir, "*.mme"))
                {
                    files++;
                    int[] code = MemoryMarshal.Cast<byte, int>(File.ReadAllBytes(f)).ToArray();
                    progs[S2AMacroAot.Hash(code)] = code;
                }
            }

            StringBuilder sb = new();
            sb.Append("// <auto-generated/> 由 ryu_judge --macrogen 生成（sw/gfx/tools/ryu_judge/core/MacroGen.cs），不要手改。输入：")
              .Append(string.Join(' ', args[1..].Select(Path.GetFileName))).Append('\n');
            sb.Append("#pragma warning disable CS0162, CS0164, CS0168, CS0219\n");
            sb.Append("using Ryujinx.Graphics.Device;\nusing System.Collections.Generic;\n\n");
            sb.Append("namespace Ryujinx.Graphics.Gpu.Engine.MME\n{\n    static partial class S2AMacroAot\n    {\n");
            sb.Append("        static partial void Register(Dictionary<ulong, Entry> table)\n        {\n");

            List<(ulong, int[])> ok = new();
            int skipped = 0;

            foreach ((ulong h, int[] code) in progs)
            {
                // 导出时的宏内存在程序尾后还有内容；这里只拿到 [0, E+1]，补两个 0 字让 Analyze 的「E+2 仍在内存内」成立（不改变 E 的位置：E 已是第一个满足条件的字）
                int[] padded = new int[code.Length + 2];
                code.CopyTo(padded, 0);
                int len = S2AMacroAot.Analyze(padded, out string reason);

                if (len != code.Length || reason != null)
                {
                    skipped++;
                    Console.Error.WriteLine($"跳过 {h:x16}（{code.Length} 字）：{reason ?? $"长度 {len}"}");
                    continue;
                }

                ok.Add((h, code));
                sb.Append($"            table.Add(0x{h:x16}UL, new Entry(C_{h:x16}, M_{h:x16}));\n");
            }

            sb.Append("        }\n");

            foreach ((ulong h, int[] code) in ok)
            {
                sb.Append($"\n        private static readonly int[] C_{h:x16} = {{ ");
                sb.Append(string.Join(", ", code.Select(w => $"unchecked((int)0x{(uint)w:x8})")));
                sb.Append(" };\n\n");
                EmitMethod(sb, $"M_{h:x16}", code);
            }

            sb.Append("    }\n}\n");

            string tmp = outPath + ".tmp";
            File.WriteAllText(tmp, sb.ToString(), new UTF8Encoding(false));
            File.Move(tmp, outPath, true);
            Console.WriteLine($"macrogen：读 {files} 个文件、去重后 {progs.Count} 个程序；编 {ok.Count} 个、跳过 {skipped} 个 → {outPath}");
            return 0;
        }

        static string I(int v) => v < 0 ? $"({v.ToString(CultureInfo.InvariantCulture)})" : v.ToString(CultureInfo.InvariantCulture);

        static string Gpr(int index) => index == 0 ? "0" : $"r{index}";

        static string GprA(int op) => Gpr((op >> 11) & 7);

        static string GprB(int op) => Gpr((op >> 14) & 7);

        static void EmitMethod(StringBuilder sb, string name, int[] code)
        {
            int e = code.Length - 2;
            HashSet<int> targets = new();

            for (int p = 0; p <= e; p++)
            {
                if ((code[p] & 7) == 7)
                {
                    targets.Add(p + (code[p] >> 14));
                }
            }

            sb.Append($"        private static void {name}(MacroJitContext ctx, IDeviceState s, int arg0, ref S2AMacroRegs o)\n        {{\n");
            sb.Append("            unchecked\n            {\n");
            sb.Append("            int r1 = arg0, r2 = 0, r3 = 0, r4 = 0, r5 = 0, r6 = 0, r7 = 0, ma = 0, mi = 0, t;\n");
            sb.Append("            bool c = false;\n            ulong u;\n");

            for (int p = 0; p <= e; p++)
            {
                int op = code[p];

                if (targets.Contains(p))
                {
                    sb.Append($"        L{p}:\n");
                }

                sb.Append($"            // {p}: 0x{(uint)op:x8}\n");

                if ((op & 7) != 7)
                {
                    EmitAlu(sb, op, "            ");

                    if ((op & 0x80) != 0)
                    {
                        EmitExit(sb, code, p);
                    }

                    continue;
                }

                // 分支：照解释器，判 GprA；跳转时延迟槽那条照常执行但其退出标志不看（noDelays 则不执行）；不跳时本条的退出标志照看
                bool onNotZero = ((op >> 4) & 1) != 0;
                string cond = onNotZero ? $"{GprA(op)} != 0" : $"{GprA(op)} == 0";
                sb.Append($"            if ({cond})\n            {{\n");

                if ((op & 0x20) == 0)
                {
                    sb.Append($"                // 延迟槽 {p + 1}: 0x{(uint)code[p + 1]:x8}\n");
                    EmitAlu(sb, code[p + 1], "                ");
                }

                sb.Append($"                goto L{p + (op >> 14)};\n            }}\n");

                if ((op & 0x80) != 0)
                {
                    EmitExit(sb, code, p);
                }
            }

            sb.Append("        Lexit:\n");
            sb.Append("            o.R1 = r1; o.R2 = r2; o.R3 = r3; o.R4 = r4; o.R5 = r5; o.R6 = r6; o.R7 = r7; o.Carry = c; o.MethAddr = ma; o.MethIncr = mi;\n");
            sb.Append("            }\n        }\n");
        }

        // 退出：照硬件（解释器 Execute 末尾那一步）再执行下一条，然后返回
        static void EmitExit(StringBuilder sb, int[] code, int p)
        {
            sb.Append("            {\n");
            sb.Append($"                // 退出后再执行 {p + 1}: 0x{(uint)code[p + 1]:x8}\n");
            EmitAlu(sb, code[p + 1], "                ");
            sb.Append("                goto Lexit;\n            }\n");
        }

        // 一条非分支指令：先求 ALU 结果（含进位更新 / 读寄存器），再按赋值方式写目的寄存器 / 方法地址 / 发送；顺序与 MacroInterpreter.Step 相同
        static void EmitAlu(StringBuilder sb, int op, string ind)
        {
            string a = GprA(op), b = GprB(op);
            int imm = op >> 14;

            switch (op & 7)
            {
                case 0:
                    switch ((op >> 17) & 0x1f)
                    {
                        case 0: sb.Append($"{ind}u = (ulong){a} + (ulong){b}; c = u > 0xffffffff; t = (int)u;\n"); break;
                        case 1: sb.Append($"{ind}u = (ulong){a} + (ulong){b} + (c ? 1UL : 0UL); c = u > 0xffffffff; t = (int)u;\n"); break;
                        case 2: sb.Append($"{ind}u = (ulong){a} - (ulong){b}; c = u < 0x100000000; t = (int)u;\n"); break;
                        case 3: sb.Append($"{ind}u = (ulong){a} - (ulong){b} - (c ? 0UL : 1UL); c = u < 0x100000000; t = (int)u;\n"); break;
                        case 8: sb.Append($"{ind}t = {a} ^ {b};\n"); break;
                        case 9: sb.Append($"{ind}t = {a} | {b};\n"); break;
                        case 10: sb.Append($"{ind}t = {a} & {b};\n"); break;
                        case 11: sb.Append($"{ind}t = {a} & ~{b};\n"); break;
                        case 12: sb.Append($"{ind}t = ~({a} & {b});\n"); break;
                        default: throw new InvalidOperationException($"非法 AluReg 0x{op:x8}（Analyze 应已拒绝）");
                    }

                    break;
                case 1:
                    sb.Append($"{ind}t = {a} + {I(imm)};\n");
                    break;
                case 2:
                case 3:
                case 4:
                    int bfSrcBit = (op >> 17) & 0x1f;
                    int bfSize = (op >> 22) & 0x1f;
                    int bfDstBit = (op >> 27) & 0x1f;
                    int bfMask = (1 << bfSize) - 1;

                    switch (op & 7)
                    {
                        case 2: sb.Append($"{ind}t = ({a} & {I(~(bfMask << bfDstBit))}) | ((((int)((uint){b} >> {bfSrcBit})) & {I(bfMask)}) << {bfDstBit});\n"); break;
                        case 3: sb.Append($"{ind}t = (((int)((uint){b} >> {a})) & {I(bfMask)}) << {bfDstBit};\n"); break;
                        case 4: sb.Append($"{ind}t = (((int)((uint){b} >> {bfSrcBit})) & {I(bfMask)}) << {a};\n"); break;
                    }

                    break;
                case 5:
                    sb.Append($"{ind}t = s.Read(({a} + {I(imm)}) * 4);\n");
                    break;
                default:
                    throw new InvalidOperationException($"非法操作 0x{op:x8}（Analyze 应已拒绝）");
            }

            int d = (op >> 8) & 7;
            string Dst(string v) => d == 0 ? $"_ = {v};" : $"r{d} = {v};";
            const string Maddr = "ma = t & 0xfff; mi = (t >> 12) & 0x3f;";
            static string Send(string v) => $"s.Write(ma * 4, {v}); ma += mi;";

            string body = ((op >> 4) & 7) switch
            {
                0 => Dst("ctx.FetchParam()"),                                          // IgnoreAndFetch
                1 => Dst("t"),                                                         // Move
                2 => $"{Dst("t")} {Maddr}",                                            // MoveAndSetMaddr
                3 => $"{Dst("ctx.FetchParam()")} {Send("t")}",                         // FetchAndSend
                4 => $"{Dst("t")} {Send("t")}",                                        // MoveAndSend
                5 => $"{Dst("ctx.FetchParam()")} {Maddr}",                             // FetchAndSetMaddr
                6 => $"{Dst("t")} {Maddr} {Send("ctx.FetchParam()")}",                 // MoveAndSetMaddrThenFetchAndSend
                _ => $"{Dst("t")} {Maddr} {Send("(t >> 12) & 0x3f")}",                 // MoveAndSetMaddrThenSendHigh
            };

            sb.Append(ind).Append(body).Append('\n');
        }
    }
}
