#!/usr/bin/env python3
"""直连翻译闭包（W2.1）：决定"翻译语义"的源码/资源/包锁文件的规范摘要。

规则 s2a-direct-closure-v2：
  0. v2 相对 v1 增加两项输入：直连编译器**自己的工程文件**（*.csproj）与**有效构建选项**
     （DefineConstants / LangVersion / Nullable / Optimize / Deterministic，由 targets 传
     --options）。v1 只纳入编译器 *.cs，改 csproj 或 DefineConstants 不会让身份失效。
  1. 输入是真正影响翻译输出的文件：直连编译器自身源码，以及它编译时用到的
     Ryujinx.Graphics.{Gpu,Shader,GAL,Texture,Device}、Ryujinx.Common、Spv.Generator
     的源码/嵌入 GLSL 与工程文件，再加大目录下的包锁文件
     （Directory.Build.props / Directory.Packages.props / global.json / nuget.config）。
  2. 路径一律取仓库相对路径（POSIX 分隔），按字节序排序；内容取工作树字节。
     不含绝对路径、时间戳、游戏名、仓库 HEAD、文档与未参与编译的脚本。
  3. 摘要 = SHA-256(规范 JSON {rule, files:[{path,bytes,sha256}...]})；
     对外值 = "s2a-dc1-" + 摘要（小写十六进制，字符集满足描述符与编译器的 closure 校验）。
  4. 排除不参与翻译的依赖（Cpu / ARMeilleure / Memory，见 EXCLUDED）：
     它们的改动不改变翻译输出，纳入只会让已发布程序库无谓失效。

用法：
  构建期（DirectClosure.targets 调）：
    closure.py --root <仓库> --list <路径清单> --cs <生成的 .g.cs>
  生产者/设备核对：
    closure.py --root <仓库> --list <路径清单> --json | --print
  回归：
    closure.py ... --check <已有的 .g.cs>      # 生成结果与源码是否仍一致
    closure.py --audit --root <仓库> --project <csproj> --cover <目录>...   # 覆盖性
    closure.py --selftest                      # 不依赖 MSBuild 的规则自检
"""

import argparse
import hashlib
import json
import os
import re
import sys
import tempfile
from pathlib import Path

RULE = "s2a-direct-closure-v2"
PREFIX = "s2a-dc1-"

# 编译进产物但不影响翻译输出：纳入只会让程序库随无关改动失效。
EXCLUDED = {
    "Ryujinx.Cpu": "CPU 模拟/翻译入口，直连翻译不经过",
    "ARMeilleure": "Ryujinx.Cpu 的传递依赖（ARM 指令模拟）",
    "Ryujinx.Memory": "客户机内存映射实现，不影响翻译输出",
}


def fail(message):
    sys.exit("🔴 direct closure：" + message)


def rel_path(path, root):
    p = Path(path)
    if not p.is_absolute():
        p = root / p
    try:
        return p.resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        fail("路径不在仓库内：" + str(path))


def file_record(root, rel):
    path = root / rel
    if not path.is_file():
        fail("清单里的文件不存在：" + rel)
    digest = hashlib.sha256()
    size = 0
    with path.open("rb") as stream:
        while block := stream.read(1 << 20):
            digest.update(block)
            size += len(block)
    return {"path": rel, "bytes": size, "sha256": digest.hexdigest()}


def compute(root, list_path, options=""):
    seen, rels = set(), []
    for line in Path(list_path).read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line:
            continue
        rel = rel_path(line, root)
        if rel not in seen:
            seen.add(rel)
            rels.append(rel)
    if not rels:
        fail("清单为空：" + str(list_path))
    rels.sort()
    records = [file_record(root, rel) for rel in rels]
    # 构建选项进摘要：同一批源文件、不同 DefineConstants/LangVersion 也是不同翻译语义。
    material = json.dumps({"rule": RULE, "options": options, "files": records}, sort_keys=True,
                          separators=(",", ":"), ensure_ascii=True).encode("utf-8")
    return hashlib.sha256(material).hexdigest(), records


def cs_escape(text):
    return text.replace("\\", "\\\\").replace("\"", "\\\"")


def cs_options(text):
    """从生成文件里读回 CompilerOptions（--check 用它重算，不必知道构建属性）。"""
    match = re.search(r'public const string CompilerOptions = "(.*)";', text)
    if not match:
        fail("生成文件里没有 CompilerOptions，无法核对")
    return match.group(1).replace("\\\"", "\"").replace("\\\\", "\\")


def render_cs(digest, records, options=""):
    total = sum(item["bytes"] for item in records)
    return (
        "// <auto-generated>\n"
        "// 由 graphics/tools/direct/compiler/closure.py 生成，不要手改。\n"
        "// 规则 " + RULE + "：影响翻译输出的源/资源与包锁文件按仓库相对路径排序后做 SHA-256。\n"
        "namespace S2A.DirectCompiler\n"
        "{\n"
        "    public static class DirectBuildIdentity\n"
        "    {\n"
        "        public const string Rule = \"" + RULE + "\";\n"
        "        public const string TranslatorClosure = \"" + PREFIX + digest + "\";\n"
        "        public const string SourcesDigest = \"sha256-" + digest + "\";\n"
        "        // 构建选项原文：--check 用它重算，避免「源码没变但选项变了」被当成一致。\n"
        "        public const string CompilerOptions = \"" + cs_escape(options) + "\";\n"
        "        public const int SourceCount = " + str(len(records)) + ";\n"
        "        public const long SourceBytes = " + str(total) + ";\n"
        "    }\n"
        "}\n"
    )


def write_if_changed(path, text):
    target = Path(path)
    if target.is_file() and target.read_text(encoding="utf-8") == text:
        return False
    target.parent.mkdir(parents=True, exist_ok=True)
    staging = target.with_name(target.name + ".tmp")
    staging.write_text(text, encoding="utf-8")
    os.replace(staging, target)
    return True


def project_properties(path, text):
    """只认工程里直接写的 <Name>Value</Name> 与 MSBuildThisFileDirectory；解析不了就报红。"""
    values = {"MSBuildThisFileDirectory": path.parent.as_posix() + "/"}
    for name, value in re.findall(r'<(\w+)(?:\s+Condition="[^"]*")?>([^<]*)</\1>', text):
        values.setdefault(name, value)
    return values


def expand(project, text, value):
    for _ in range(6):
        if "$(" not in value:
            return value
        name = re.search(r"\$\((\w+)\)", value).group(1)
        if name not in project_properties(project, text):
            fail("工程引用里的 MSBuild 属性无法定位：" + value)
        value = value.replace("$(" + name + ")", project_properties(project, text)[name])
    fail("工程引用展开层数过深：" + value)


def audit(root, project, covers):
    covers = [Path(c).resolve() for c in covers]
    seen, queue, missing, projects = set(), [Path(project).resolve()], [], []
    while queue:
        current = queue.pop()
        if current in seen:
            continue
        if not current.is_file():
            fail("引用的工程不存在：" + str(current))
        seen.add(current)
        text = current.read_text(encoding="utf-8-sig")
        projects.append(current.stem)
        inside = any(current.parent == cover or cover in current.parent.parents for cover in covers)
        if not inside and current.stem not in EXCLUDED:
            missing.append(str(current) + "：不在任何 --cover 目录下")
        for match in re.finditer(r'<ProjectReference\s+Include="([^"]+)"', text):
            raw = match.group(1).replace("\\", "/")
            if "$(" in raw:
                raw = expand(current, text, raw)
            queue.append((current.parent / raw).resolve())
    for path in sorted(seen):
        text = path.read_text(encoding="utf-8-sig")
        if re.search(r"<EnableDefaultCompileItems>\s*false\s*</EnableDefaultCompileItems>", text):
            missing.append(str(path) + "：关闭了默认编译项，目录通配无法如实覆盖")
        for match in re.finditer(r'<Compile\s+Include="([^"]+)"', text):
            target = (path.parent / match.group(1).replace("\\", "/")).resolve()
            if target.parent != path.parent and not any(
                    target == cover or cover in target.parents for cover in covers):
                missing.append(str(path) + "：链接了目录外的编译文件 " + str(target))
    if missing:
        fail("闭包覆盖不全：\n  " + "\n  ".join(missing))
    print("direct closure audit: " + str(len(seen)) + " 个工程（" + ", ".join(sorted(projects)) +
          "），覆盖目录 " + ", ".join(str(c) for c in covers))


def selftest():
    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        (root / "src").mkdir()
        (root / "src/a.cs").write_text("class A {}", encoding="utf-8")
        (root / "src/b.cs").write_text("class B {}", encoding="utf-8")
        (root / "doc.md").write_text("notes", encoding="utf-8")
        listing = root / "list.txt"
        listing.write_text(str(root / "src/a.cs") + "\n" + str(root / "src/b.cs") + "\n",
                           encoding="utf-8")
        first, _ = compute(root, listing)
        second, _ = compute(root, listing)
        assert first == second, "同输入两次摘要不同"
        (root / "doc.md").write_text("changed notes", encoding="utf-8")
        assert compute(root, listing)[0] == first, "无关文档改变了摘要"
        (root / "src/b.cs").write_text("class B { int x; }", encoding="utf-8")
        moved, _ = compute(root, listing)
        assert moved != first, "翻译源改动没有改变摘要"
        (root / "other").mkdir()
        (root / "other/c.cs").write_text("class C {}", encoding="utf-8")
        os.replace(root / "src/b.cs", root / "other/c.cs")
        listing.write_text(str(root / "src/a.cs") + "\n" + str(root / "other/c.cs") + "\n",
                           encoding="utf-8")
        renamed, renamed_records = compute(root, listing)
        assert renamed != moved, "换路径不改摘要（规范路径必须进入身份）"
        rendered = render_cs(renamed, renamed_records)
        assert PREFIX + renamed in rendered, "生成文件没有携带摘要"
        # v2：构建选项与工程文件必须进身份——只改 DefineConstants 也要失效。
        with_options = compute(root, listing, "DefineConstants=A")[0]
        other_options = compute(root, listing, "DefineConstants=B")[0]
        assert with_options != other_options, "构建选项改动没有改变摘要"
        assert compute(root, listing, "")[0] == renamed, "空选项改变了摘要"
        round_trip = 'DefineConstants=A;B="x"'
        assert cs_options(render_cs(with_options, renamed_records, round_trip)) == round_trip, \
            "选项写入/读回不一致"
    print("direct closure selftest: ok")


def main():
    parser = argparse.ArgumentParser(add_help=True)
    parser.add_argument("--root")
    parser.add_argument("--list")
    parser.add_argument("--cs")
    parser.add_argument("--json", action="store_true")
    parser.add_argument("--print", dest="do_print", action="store_true")
    parser.add_argument("--check")
    parser.add_argument("--audit", action="store_true")
    parser.add_argument("--selftest", action="store_true")
    parser.add_argument("--options", help="影响翻译输出的构建选项原文（由 targets 传入）")
    parser.add_argument("--project")
    parser.add_argument("--cover", action="append", default=[])
    args = parser.parse_args()

    if args.selftest:
        selftest()
        return 0

    if args.audit:
        if not args.root or not args.project or not args.cover:
            fail("--audit 需要 --root、--project 与至少一个 --cover")
        audit(Path(args.root), args.project, args.cover)
        return 0
    if not args.root or not args.list:
        fail("需要 --root 与 --list")
    root = Path(args.root)
    options = args.options or ""
    if args.check:
        # 选项从生成文件里读回：核对"源码/选项是否与嵌入值一致"不需要知道构建属性。
        actual = Path(args.check).read_text(encoding="utf-8") if Path(args.check).is_file() else ""
        if not actual:
            fail("嵌入身份文件不存在：" + str(args.check))
        digest, records = compute(root, args.list, cs_options(actual))
        closure = PREFIX + digest
        expected = render_cs(digest, records, cs_options(actual))
        if actual != expected:
            fail("嵌入身份与当前源码不一致，需要重新构建：" + str(args.check))
        print("direct closure: " + closure + " (embedded identity is current)")
        return 0
    digest, records = compute(root, args.list, options)
    closure = PREFIX + digest
    if args.do_print:
        print(closure)
    if args.json:
        print(json.dumps({"schema": "s2a-direct-identity-v1", "rule": RULE,
                          "translatorClosure": closure, "sourcesDigest": "sha256-" + digest,
                          "sources": len(records),
                          "bytes": sum(item["bytes"] for item in records)},
                         ensure_ascii=False))
    if args.cs:
        changed = write_if_changed(args.cs, render_cs(digest, records, options))
        print("direct closure: " + closure + " (" + str(len(records)) + " files, " +
              str(sum(item["bytes"] for item in records)) + " bytes" +
              (", written" if changed else ", unchanged") + ")")
    return 0


if __name__ == "__main__":
    sys.exit(main())
