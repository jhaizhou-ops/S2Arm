#!/bin/bash
# 60 帧逻辑速度同局 A/B 入账（tools/fps_ab_ledger.py merge；合成批次表，约 1 秒）：bash tests/fps_ab_ledger_test.sh
# 门禁覆盖：tools/fps_ab_ledger.py
# 期望手写（门槛同 tests/autoplay sp_verdict：原生 60 = 关段帧率 ≥ 55；帧率没涨 = 0 < q < 1.15）：
#   ① 判不出、关段 60 帧 → 入账「无风险」
#   ② 判不出、关段 30、q 1.02 → 入账「无风险」
#   ③ 判不出、关段 30、q 2.0、像素 0.5（量不出）→ 不入账
#   ④ 判不出、q 空（拍不到画面）→ 不入账
#   ⑤ 同构建号已登记红，新批次判不出原生 60 → 红保留、不覆盖
#   ⑥ 绿 / 红照旧入账
set -u
R=$(cd "$(dirname "$0")/.." && pwd); PY=${S2A_PYTHON:-python3}; T=$(mktemp -d); bad=0
ck() { if eval "$2"; then echo "通 $1"; else echo "不通 $1"; bad=$((bad + 1)); fi; }
D=$T/repo/docs/名单_60帧逻辑速度; mkdir -p $D
H='键	名称	版本	构建号	结论	ρ	q	量法	关段像素每秒	开段像素每秒	关段帧率	开段帧率	说明	日期	局目录'
b() { printf '%s\t款\t1.0\t%s\t%s\t%s\t%s\t推左摇杆走\t%s\t40\t%s\t60\t\t2026-11-04\tx\n' "$1" "$(printf '%032d' 7)" "$2" "$3" "$4" "$5" "$6"; }
printf '程序号\t构建号\t款\t结论\tρ\tq\t依据\t日期\t放行\n0100000000000500\t%s\t款\t红\t1.9\t2.0\t旧\t2026-11-02\t\n' "$(printf '%032d' 7)" > $D/0100000000000500.tsv
{ echo "$H"
  b 0100000000000100 判不出 1.0 1.0 40 60
  b 0100000000000200 判不出 1.0 1.02 40 30
  b 0100000000000300 判不出 1.0 2.0 0.5 30
  b 0100000000000400 判不出 '' '' 0 30
  b 0100000000000500 判不出 1.0 1.0 40 60
  b 0100000000000600 绿 1.0 2.0 40 30
  b 0100000000000700 红 2.0 2.0 40 30
} > $T/逻辑速度.tsv
out=$("$PY" "$R/tools/fps_ab_ledger.py" merge "$T/repo" "$T/逻辑速度.tsv")
v() { [ -f $D/$1.tsv ] && tail -1 $D/$1.tsv | cut -f4 || echo 无; }
ck "① 原生 60 → 无风险（$(v 0100000000000100)）" '[ "$(v 0100000000000100)" = 无风险 ]'
ck "② 帧率没涨 → 无风险（$(v 0100000000000200)）" '[ "$(v 0100000000000200)" = 无风险 ]'
ck "③ 量不出 → 不入账（$(v 0100000000000300)）" '[ "$(v 0100000000000300)" = 无 ]'
ck "④ q 空 → 不入账（$(v 0100000000000400)）" '[ "$(v 0100000000000400)" = 无 ]'
ck "⑤ 同构建号已红 → 红保留（$(v 0100000000000500)）" '[ "$(v 0100000000000500)" = 红 ]'
ck "⑥ 绿 / 红照旧（$(v 0100000000000600) / $(v 0100000000000700)）" '[ "$(v 0100000000000600)" = 绿 ] && [ "$(v 0100000000000700)" = 红 ]'
echo "$out" | head -2
rm -rf "$T"; [ $bad = 0 ] && echo "fps_ab_ledger 单测全过" || { echo "fps_ab_ledger 单测有不通"; exit 1; }
