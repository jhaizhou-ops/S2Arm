using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using System.Collections.Generic;
using System.Linq;

namespace Ryujinx.HLE.Generators
{
    // S2Arm: zero-allocation command dispatch for the HLE IPC framework. IpcService.CallCmifMethod / CallTipcMethod
    // invoke commands through MethodInfo.Invoke, which allocates on every request (argument array checks, boxed
    // ResultCode). This emits, for every IpcService subclass, a static switch over command ids calling the command
    // methods directly, plus a Type -> function pointer table that IpcService looks up once per instance.
    // Commands are found exactly like IpcService does: public (instance or static) methods with [CommandCmif] /
    // [CommandTipc], including inherited ones; a method whose return type is not an enum is left to reflection.
    [Generator]
    public class S2AIpcDispatchGenerator : ISourceGenerator
    {
        private const string IpcServiceName = "Ryujinx.HLE.HOS.Services.IpcService";

        public void Initialize(GeneratorInitializationContext context)
        {
            context.RegisterForSyntaxNotifications(() => new ServiceSyntaxReceiver());
        }

        public void Execute(GeneratorExecutionContext context)
        {
            ServiceSyntaxReceiver receiver = (ServiceSyntaxReceiver)context.SyntaxReceiver;
            INamedTypeSymbol ipcService = context.Compilation.GetTypeByMetadataName(IpcServiceName);

            if (ipcService == null)
            {
                return;
            }

            HashSet<INamedTypeSymbol> types = new(SymbolEqualityComparer.Default);

            foreach (ClassDeclarationSyntax decl in receiver.Types)
            {
                if (context.Compilation.GetSemanticModel(decl.SyntaxTree).GetDeclaredSymbol(decl) is INamedTypeSymbol t &&
                    !t.IsAbstract && !t.IsGenericType && IsAccessible(t) && DerivesFrom(t, ipcService))
                {
                    types.Add(t);
                }
            }

            CodeGenerator g = new();
            g.AppendLine("// <auto-generated/> S2Arm: see S2AIpcDispatchGenerator");
            g.AppendLine("using System.Collections.Generic;");
            g.EnterScope("namespace Ryujinx.HLE.HOS.Services");
            g.EnterScope("static unsafe class S2AIpcDispatch");
            g.AppendLine("public const long NotHandled = long.MinValue;");

            List<(string Type, string Cmif, string Tipc)> table = [];
            int n = 0;

            foreach (INamedTypeSymbol t in types.OrderBy(x => x.ToDisplayString()))
            {
                string full = t.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                string cmif = EmitSwitch(g, t, full, "CommandCmifAttribute", $"Cmif{n}");
                string tipc = EmitSwitch(g, t, full, "CommandTipcAttribute", $"Tipc{n}");
                table.Add((full, cmif, tipc));
                n++;
            }

            g.AppendLine("private static readonly Dictionary<System.Type, (nint Cmif, nint Tipc)> _table = Build();");
            g.EnterScope("private static Dictionary<System.Type, (nint Cmif, nint Tipc)> Build()");
            g.AppendLine($"Dictionary<System.Type, (nint, nint)> d = new({table.Count});");

            foreach ((string type, string cmif, string tipc) in table)
            {
                string c = cmif != null ? $"(nint)(delegate*<IpcService, int, ServiceCtx, long>)&{cmif}" : "0";
                string p = tipc != null ? $"(nint)(delegate*<IpcService, int, ServiceCtx, long>)&{tipc}" : "0";
                g.AppendLine($"d[typeof({type})] = ({c}, {p});");
            }

            g.AppendLine("return d;");
            g.LeaveScope();

            g.EnterScope("public static (nint Cmif, nint Tipc) Lookup(System.Type type)");
            g.AppendLine("return _table.TryGetValue(type, out (nint, nint) e) ? e : (0, 0);");
            g.LeaveScope();

            g.LeaveScope();
            g.LeaveScope();

            context.AddSource("S2AIpcDispatch.g.cs", g.ToString());
        }

        // Returns the emitted method name, or null when the type has no such commands
        private static string EmitSwitch(CodeGenerator g, INamedTypeSymbol type, string full, string attributeName, string name)
        {
            Dictionary<int, IMethodSymbol> commands = [];
            HashSet<string> seen = [];

            for (INamedTypeSymbol t = type; t != null; t = t.BaseType)
            {
                foreach (IMethodSymbol m in t.GetMembers().OfType<IMethodSymbol>())
                {
                    if (m.MethodKind != MethodKind.Ordinary || m.DeclaredAccessibility != Accessibility.Public || !seen.Add(m.Name + "/" + m.Parameters.Length))
                    {
                        continue;
                    }

                    foreach (AttributeData a in m.GetAttributes())
                    {
                        if (a.AttributeClass?.Name != attributeName || a.ConstructorArguments.Length < 1 || a.ConstructorArguments[0].Value is not int id)
                        {
                            continue;
                        }

                        if (m.Parameters.Length == 1 && m.Parameters[0].Type.Name == "ServiceCtx" && m.ReturnType.TypeKind == TypeKind.Enum && !commands.ContainsKey(id))
                        {
                            commands[id] = m;
                        }
                    }
                }
            }

            if (commands.Count == 0)
            {
                return null;
            }

            g.EnterScope($"private static long {name}(IpcService s, int id, ServiceCtx ctx)");
            g.EnterScope("switch (id)");

            foreach (KeyValuePair<int, IMethodSymbol> kv in commands.OrderBy(kv => kv.Key))
            {
                string call = kv.Value.IsStatic ? $"{full}.{kv.Value.Name}(ctx)" : $"(({full})s).{kv.Value.Name}(ctx)";
                g.AppendLine($"case {kv.Key}: return (long){call};");
            }

            g.AppendLine("default: return NotHandled;");
            g.LeaveScope();
            g.LeaveScope();

            return name;
        }

        private static bool DerivesFrom(INamedTypeSymbol t, INamedTypeSymbol baseType)
        {
            for (INamedTypeSymbol b = t.BaseType; b != null; b = b.BaseType)
            {
                if (SymbolEqualityComparer.Default.Equals(b, baseType))
                {
                    return true;
                }
            }

            return false;
        }

        private static bool IsAccessible(INamedTypeSymbol t)
        {
            for (INamedTypeSymbol c = t; c != null; c = c.ContainingType)
            {
                if (c.DeclaredAccessibility is Accessibility.Private or Accessibility.Protected or Accessibility.ProtectedAndInternal)
                {
                    return false;
                }
            }

            return true;
        }
    }
}
