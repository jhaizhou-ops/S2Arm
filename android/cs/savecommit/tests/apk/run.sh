set -euo pipefail
: "${ADB:?Set explicit path to an already installed adb}"
: "${ANDROID_SERIAL:?Explicitly select one authorized device}"
: "${RUN_DIR:?Set a new local evidence output directory}"
: "${EXPECTED_SOURCE_ID:?Read source_identity from the intended build-evidence.json}"
if [[ ! "$EXPECTED_SOURCE_ID" =~ ^[0-9a-f]{40}(\+dirty)?$ ]]; then
    echo 'EXPECTED_SOURCE_ID must be a full commit hash, optionally +dirty' >&2; exit 2
fi
SUITE=${1:-all}
case "$SUITE" in native) entries=(Native);; openread) entries=(OpenRead);; managed) entries=(Managed);; all) entries=(Native OpenRead);; *) echo 'Usage: run.sh [native|openread|managed|all]' >&2; exit 2;; esac
if [ -e "$RUN_DIR" ]; then echo 'RUN_DIR must not exist; preserve earlier evidence' >&2; exit 2; fi
mkdir -p "$RUN_DIR"
PACKAGE=org.s2arm.probe.savecommit.moongrant
failure=0
for entry in "${entries[@]}"; do
    # Does not install, clear data, launch UI, change permissions or run another app.
    if ! "$ADB" -s "$ANDROID_SERIAL" shell am instrument -w -r "$PACKAGE/.${entry}Instrumentation" > "$RUN_DIR/$entry.instrumentation.txt" 2>&1; then
        echo "$entry: instrumentation transport failed" >&2; failure=1; continue
    fi
    path=$(sed -n 's/^INSTRUMENTATION_RESULT: run_directory=//p' "$RUN_DIR/$entry.instrumentation.txt" | tr -d '\r')
    # Only paths generated by this package are eligible for readback. No shell metacharacters.
    if [[ ! "$path" =~ ^/data/(user/0|data)/org\.s2arm\.probe\.savecommit\.moongrant/files/(Native|OpenRead|Managed)-[0-9]+$ ]]; then
        echo "$entry: missing/unexpected private run path; inspect instrumentation output" >&2; failure=1; continue
    fi
    if [[ "${path##*/}" != "$entry-"* ]]; then
        echo "$entry: wrong suite private run directory; no readback performed" >&2; failure=1; continue
    fi
    for file in status.txt stdout.log stderr.log harness.log; do
        if ! "$ADB" -s "$ANDROID_SERIAL" shell run-as "$PACKAGE" cat "$path/$file" > "$RUN_DIR/$entry.$file" 2>&1; then failure=1; fi
    done
    # Require framework and Java completion as well as native completion. A native
    # RETURNED record can precede Java evidence failure or process termination.
    # Exact extracted values reject missing, duplicate, or contradictory fields.
    instrumentation=$(tr -d '\r' < "$RUN_DIR/$entry.instrumentation.txt")
    if [ "$(printf '%s\n' "$instrumentation" | sed -n 's/^INSTRUMENTATION_RESULT: suite=//p')" != "$entry" ] ||
       [ "$(printf '%s\n' "$instrumentation" | sed -n 's/^INSTRUMENTATION_RESULT: harness_state=//p')" != JNI_RETURNED ] ||
       [ "$(printf '%s\n' "$instrumentation" | sed -n 's/^INSTRUMENTATION_RESULT: wrapper_return_code=//p')" != 0 ] ||
       [ "$(printf '%s\n' "$instrumentation" | sed -n 's/^INSTRUMENTATION_CODE: //p')" != -1 ] ||
       printf '%s\n' "$instrumentation" | grep -Eq '^INSTRUMENTATION_(FAILED|ABORTED):|^INSTRUMENTATION_RESULT: exception='; then
        echo "$entry: Java/framework did not complete successfully; retain all logs" >&2; failure=1
    fi
    # Never equate adb/am exit zero with a suite pass. No filtering or retry-to-green.
    if ! grep -Fqx "source_commit=$EXPECTED_SOURCE_ID" "$RUN_DIR/$entry.status.txt" ||
       ! grep -qx 'state=RETURNED' "$RUN_DIR/$entry.status.txt" ||
       ! grep -qx 'suite_return_code=0' "$RUN_DIR/$entry.status.txt" ||
       grep -q 'state=CLEANUP_ERROR' "$RUN_DIR/$entry.status.txt" ||
       ! grep -q 'selinux=.*untrusted_app' "$RUN_DIR/$entry.status.txt"; then
        echo "$entry: not an APP-domain suite pass; retain all logs" >&2; failure=1
    fi
    if [ "$entry" = Managed ] && ! grep -qx 'savecommit managed: 21 checks, 0 failures' "$RUN_DIR/$entry.stdout.log"; then
        echo "Managed: missing full managed check count" >&2; failure=1
    fi
    cat "$RUN_DIR/$entry.status.txt" "$RUN_DIR/$entry.stdout.log"
done
exit "$failure"
