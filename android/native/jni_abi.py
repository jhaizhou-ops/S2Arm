#!/usr/bin/env python3
"""JNI ABI identity of the Java side: SHA-256 over "Class.method(Param,...)Return" of every
native method declared in the given Java sources, sorted, one per line, simple type names, varargs
as arrays: what RuntimeLibrary.jniAbi computes by reflection at run time. The build bakes it into
libs2arm_android.so (s2a_jni_abi.h -> NativeBridge.jniAbi()), and verify-apk.py checks the APK's
library carries the value of these sources, so a library built against other native declarations
than the installed Java is refused before any other native call.

Every `native` modifier in a source must belong to a declaration this parser understands (any
modifier order, static or not, varargs); anything else (generic types, unparsed declarations) is
an error rather than a hash that would differ from the reflection one.

    jni_abi.py --header <out.h> <Class.java>...   write the header (only when its bytes change)
    jni_abi.py <Class.java>...                    print the canonical lines and the hash
"""
import hashlib
import re
import sys
from pathlib import Path

MODIFIERS = r"(?:public|protected|private|static|final|native|synchronized|strictfp)"
DECL = re.compile(rf"((?:\b{MODIFIERS}\s+)+)([\w.$\[\]]+)\s+(\w+)\s*\(([^)]*)\)\s*;")
STRIP = re.compile(r'//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\\n])*"|\'(?:\\.|[^\'\\\n])*\'', re.S)


class Unsupported(Exception):
    pass


def simple(java_type):
    t = re.sub(r"\s+", "", java_type)
    if "<" in t or ">" in t:
        raise Unsupported("generic type " + t)
    if t.endswith("..."):
        t = t[:-3] + "[]"
    base = t.rstrip("[]")
    return base.split(".")[-1] + t[len(base):]


def entries(path):
    text = STRIP.sub(" ", Path(path).read_text(encoding="utf-8"))
    found = []
    for modifiers, ret, name, params in DECL.findall(text):
        if "native" not in modifiers.split():
            continue
        types = []
        for param in filter(None, (p.strip() for p in params.split(","))):
            words = [w for w in param.replace("...", "... ").split() if w != "final" and not w.startswith("@")]
            if len(words) < 2:
                raise Unsupported(f"{path}: parameter '{param}' of {name}")
            name_dims = words[-1][words[-1].find("["):] if "[" in words[-1] else ""   # C-style `int values[]`
            types.append(simple("".join(words[:-1]) + name_dims))
        found.append(f"{Path(path).stem}.{name}({','.join(types)}){simple(ret)}")
    natives = len(re.findall(r"\bnative\b", text))
    if natives != len(found):
        raise Unsupported(f"{path}: {natives} native modifiers, {len(found)} declarations understood")
    return found


def identity(paths):
    try:
        lines = sorted(e for p in paths for e in entries(p))
    except Unsupported as error:
        raise SystemExit("jni_abi.py: " + str(error))
    if not lines:
        raise SystemExit("jni_abi.py: no native declarations in " + ", ".join(map(str, paths)))
    return lines, hashlib.sha256("\n".join(lines).encode()).hexdigest()


def main(argv):
    if argv[:1] == ["--header"]:
        out, sources = Path(argv[1]), argv[2:]
        lines, digest = identity(sources)
        text = ("// Generated by android/native/jni_abi.py from " + ", ".join(Path(s).name for s in sources)
                + "; do not edit.\n// " + "\n// ".join(lines) + f'\n#define S2A_JNI_ABI_SHA256 "{digest}"\n')
        if not out.exists() or out.read_text() != text:
            out.write_text(text)
        return 0
    lines, digest = identity(argv)
    print("\n".join(lines))
    print(digest)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
