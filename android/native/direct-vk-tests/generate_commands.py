#!/usr/bin/env python3
# 门禁手动：辅助脚本（用例生成器），从已装 Khronos/NDK 头重生成 direct_vk_commands.inc，本身不是单测
"""Regenerate reviewed bridge signatures from the installed Khronos/NDK header."""
import argparse
from pathlib import Path
import re


ALLOCATIONS = """vkAllocateMemory vkCreateBuffer vkCreateBufferView vkCreateCommandPool
vkCreateDescriptorPool vkCreateDescriptorSetLayout vkCreateDescriptorUpdateTemplate vkCreateDescriptorUpdateTemplateKHR vkCreateFence vkCreateFramebuffer
vkCreateGraphicsPipelines vkCreateImage vkCreateImageView vkCreatePipelineLayout
vkCreateRenderPass vkCreateSampler vkCreateSemaphore vkCreateShaderModule vkCreateSwapchainKHR
vkDestroyBuffer vkDestroyBufferView vkDestroyCommandPool vkDestroyDescriptorPool
vkDestroyDescriptorSetLayout vkDestroyDescriptorUpdateTemplate vkDestroyDescriptorUpdateTemplateKHR vkDestroyFence vkDestroyFramebuffer
vkDestroyImage vkDestroyImageView vkDestroyPipeline vkDestroyPipelineLayout vkDestroyRenderPass
vkDestroySampler vkDestroySemaphore vkDestroyShaderModule vkDestroySwapchainKHR vkFreeMemory""".split()
BLOCKING = """vkAcquireNextImageKHR vkQueueBindSparse vkQueuePresentKHR vkQueueSubmit
vkQueueWaitIdle vkWaitForFences""".split()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--header", required=True, type=Path)
    parser.add_argument("--out", required=True, type=Path)
    args = parser.parse_args()
    header = args.header.read_text()
    rows = ["// Generated by direct-vk-tests/generate_commands.py from Khronos Vulkan prototypes."]
    for name in sorted(ALLOCATIONS + BLOCKING):
        found = re.findall(r"VKAPI_ATTR (\w+) VKAPI_CALL " + name + r"\((.*?)\);", header, re.S)
        if len(found) != 1:
            raise ValueError(f"ambiguous/missing prototype: {name}")
        result, params = found[0]
        params = re.sub(r"\s+", " ", params).strip()
        names = [re.search(r"(\w+)(?:\[[^]]+\])?$", p.strip()).group(1) for p in params.split(",")]
        if name in ALLOCATIONS:
            assert "pAllocator" in names and result in ("void", "VkResult")
            macro = "ALLOC_VOID" if result == "void" else "ALLOC_RESULT"
            handle = re.search(r"\b(Vk\w+)\*?\s+\w+\s*$", params.split(",")[-1] if result != "void" else params.split(",")[1]).group(1)
            types = {"VkDeviceMemory":"DEVICE_MEMORY", "VkBuffer":"BUFFER", "VkBufferView":"BUFFER_VIEW",
                "VkCommandPool":"COMMAND_POOL", "VkDescriptorPool":"DESCRIPTOR_POOL", "VkDescriptorSetLayout":"DESCRIPTOR_SET_LAYOUT",
                "VkDescriptorUpdateTemplate":"DESCRIPTOR_UPDATE_TEMPLATE", "VkDescriptorUpdateTemplateKHR":"DESCRIPTOR_UPDATE_TEMPLATE",
                "VkFence":"FENCE", "VkFramebuffer":"FRAMEBUFFER", "VkPipeline":"PIPELINE", "VkImage":"IMAGE",
                "VkImageView":"IMAGE_VIEW", "VkPipelineLayout":"PIPELINE_LAYOUT", "VkRenderPass":"RENDER_PASS",
                "VkSampler":"SAMPLER", "VkSemaphore":"SEMAPHORE", "VkShaderModule":"SHADER_MODULE", "VkSwapchainKHR":"SWAPCHAIN_KHR"}
            metadata = ", VK_OBJECT_TYPE_" + types[handle]
            if result == "void": metadata += ", " + names[1]
            else: metadata += ", " + ("createInfoCount" if name=="vkCreateGraphicsPipelines" else "1") + ", " + names[-1]
        else:
            assert result == "VkResult"
            macro = "BLOCK_RESULT"
            metadata = ""
        rows.append(f"{macro}({name}, ({params}), ({', '.join(names)}){metadata})")
    args.out.write_text("\n".join(rows) + "\n")


if __name__ == "__main__":
    main()
